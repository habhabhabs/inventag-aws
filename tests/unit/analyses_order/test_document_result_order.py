"""A4: the list of generation results follows the order of the requested formats.

Formats are generated by three threads and finish in any order. The results
(and so the errors and warnings of the summary) must not depend on that.
"""

import concurrent.futures
import threading

import pytest

from inventag.reporting.document_generator import (
    DocumentConfig,
    DocumentGenerationResult,
    DocumentGenerator,
)

FORMATS = ["excel", "word", "csv", "json"]


def _generator(tmp_path, **over):
    config = DocumentConfig(
        output_formats=list(FORMATS),
        output_directory=str(tmp_path),
        max_worker_threads=len(FORMATS),
        **over,
    )
    return DocumentGenerator(config)


def _finish_in_reverse(generator, failing=()):
    """Make format i wait until format i+1 is done, so they finish in reverse."""
    done = {fmt: threading.Event() for fmt in FORMATS}
    started = threading.Barrier(len(FORMATS))

    def fake(bom_data, fmt):
        started.wait(timeout=10)
        index = FORMATS.index(fmt)
        if index + 1 < len(FORMATS):
            assert done[FORMATS[index + 1]].wait(timeout=10)
        done[fmt].set()
        if fmt in failing:
            raise RuntimeError(f"{fmt} broke")
        return DocumentGenerationResult(
            format_type=fmt, filename=f"{fmt}.out", success=True
        )

    generator._generate_single_document = fake


def test_results_are_in_the_order_of_the_formats(tmp_path):
    generator = _generator(tmp_path)
    _finish_in_reverse(generator)
    results = generator._parallel_document_generation(object(), list(FORMATS))
    assert [r.format_type for r in results] == FORMATS


def test_a_failed_format_keeps_its_place(tmp_path):
    generator = _generator(tmp_path)
    _finish_in_reverse(generator, failing={"word"})
    results = generator._parallel_document_generation(object(), list(FORMATS))
    assert [r.format_type for r in results] == FORMATS
    assert [r.success for r in results] == [True, False, True, True]
    assert results[1].error_message == "word broke"


def test_the_overall_time_limit_still_raises_timeout(tmp_path):
    generator = _generator(tmp_path, generation_timeout=0.05)
    release = threading.Event()

    def stuck(bom_data, fmt):
        release.wait(timeout=10)
        return DocumentGenerationResult(format_type=fmt, filename="x", success=True)

    generator._generate_single_document = stuck
    # Only a clean-up: the pool waits for its threads when the error leaves it.
    cleanup = threading.Timer(1.0, release.set)
    cleanup.start()
    try:
        with pytest.raises(concurrent.futures.TimeoutError):
            generator._parallel_document_generation(object(), list(FORMATS))
    finally:
        release.set()
        cleanup.cancel()
